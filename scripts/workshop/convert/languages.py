def locale_code(language):
    """把 ISO 语言名转成 MOBI 的 locale 字段（4 字节）。

    没有对应条目时用英文。
    """
    text = (language or '').strip()
    if '-' in text:
        base, _, region = text.partition('-')
    else:
        base, region = text, ''
    base = base.lower()
    region = region.upper()
    entry = LANGUAGE_CODES.get(base)
    if entry is None:
        entry = LANGUAGE_CODES.get('en')
        region = ''
    if region and region in entry:
        lang, sub = entry[region]
    else:
        lang, sub = entry['']
    return bytes((0, 0, sub, lang))
